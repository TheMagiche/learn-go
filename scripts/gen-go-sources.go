// Command gen-go-sources copies Go functions into the React app so the
// learning panel can show the handler that served a click.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}
	snippets, err := collect(root)
	if err != nil {
		fatal(err)
	}
	concepts, err := handlerConcepts(filepath.Join(root, "internal", "learn", "trace.go"))
	if err != nil {
		fatal(err)
	}
	var buf bytes.Buffer
	buf.WriteString("// Generated by scripts/gen-go-sources.go. Do not edit by hand.\n")
	buf.WriteString("// Run `make gen` after changing Go sources.\n\n")
	buf.WriteString("export type GoSource = {\n")
	buf.WriteString("  file: string;\n")
	buf.WriteString("  startLine: number;\n")
	buf.WriteString("  code: string;\n")
	buf.WriteString("};\n\n")
	buf.WriteString("export const goSources: Record<string, GoSource> = {\n")
	keys := make([]string, 0, len(snippets))
	for k := range snippets {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, key := range keys {
		sn := snippets[key]
		buf.WriteString("  " + strconv.Quote(key) + ": {\n")
		buf.WriteString("    file: " + strconv.Quote(sn.file) + ",\n")
		buf.WriteString("    startLine: " + strconv.Itoa(sn.start) + ",\n")
		buf.WriteString("    code: " + strconv.Quote(sn.code) + ",\n")
		buf.WriteString("  },\n")
	}
	buf.WriteString("};\n\n")
	buf.WriteString("export const handlerConcepts: Record<string, string[]> = {\n")
	hkeys := make([]string, 0, len(concepts))
	for k := range concepts {
		hkeys = append(hkeys, k)
	}
	sort.Strings(hkeys)
	for _, key := range hkeys {
		ids := make([]string, len(concepts[key]))
		for i, id := range concepts[key] {
			ids[i] = strconv.Quote(id)
		}
		buf.WriteString("  " + strconv.Quote(key) + ": [" + strings.Join(ids, ", ") + "],\n")
	}
	buf.WriteString("};\n")

	out := filepath.Join(root, "web", "src", "learn", "goSources.ts")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(out, buf.Bytes(), 0o644); err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d snippets)\n", out, len(snippets))
}

type snippet struct {
	file  string
	start int
	code  string
}

func collect(root string) (map[string]snippet, error) {
	// LEARN(go-ast): parser.ParseFile turns a .go file into an ast.File, a tree of declarations. We walk each FuncDecl, then slice the original source from the function's start line to its end line. The React app shows that slice when a response names the function.
	dirs := []string{
		filepath.Join(root, "cmd"),
		filepath.Join(root, "internal"),
		filepath.Join(root, "scripts"),
		filepath.Join(root, "web"),
	}
	var files []string
	for _, dir := range dirs {
		err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				switch d.Name() {
				case "node_modules", "dist":
					return filepath.SkipDir
				}
				return nil
			}
			if strings.HasSuffix(path, ".go") {
				files = append(files, path)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Strings(files)

	type item struct {
		name  string
		file  string
		recv  string
		pkg   string
		start int
		code  string
	}
	var items []item
	for _, path := range files {
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return nil, err
		}
		rel = filepath.ToSlash(rel)
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		lines := strings.Split(string(src), "\n")
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Body == nil {
				continue
			}
			startTok := fn.Pos()
			if fn.Doc != nil {
				startTok = fn.Doc.Pos()
			}
			start := fset.Position(startTok).Line
			end := fset.Position(fn.End()).Line
			if start < 1 || end > len(lines) || end < start {
				continue
			}
			recv := ""
			if fn.Recv != nil && len(fn.Recv.List) > 0 {
				recv = typeName(fn.Recv.List[0].Type)
			}
			items = append(items, item{
				name:  fn.Name.Name,
				file:  rel,
				recv:  recv,
				pkg:   file.Name.Name,
				start: start,
				code:  strings.Join(lines[start-1:end], "\n"),
			})
		}
	}

	counts := map[string]int{}
	for _, it := range items {
		counts[it.name]++
	}
	out := map[string]snippet{}
	for _, it := range items {
		key := it.name
		if it.recv == "List" {
			key = "List." + it.name
		} else if counts[it.name] > 1 {
			if it.recv != "" {
				key = it.recv + "." + it.name
			} else {
				key = it.pkg + "." + it.name
			}
		}
		if _, exists := out[key]; exists {
			key = it.pkg + "." + it.file + "." + it.name
		}
		out[key] = snippet{file: it.file, start: it.start, code: it.code}
	}
	return out, nil
}

func typeName(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return typeName(t.X)
	case *ast.IndexExpr:
		return typeName(t.X)
	default:
		return ""
	}
}

func handlerConcepts(path string) (map[string][]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	block := regexp.MustCompile(`(?s)"([A-Za-z0-9]+)"\s*:\s*\{(.*?)\}`)
	id := regexp.MustCompile(`"([a-z0-9-]+)"`)
	out := map[string][]string{}
	for _, m := range block.FindAllStringSubmatch(string(data), -1) {
		var ids []string
		for _, im := range id.FindAllStringSubmatch(m[2], -1) {
			ids = append(ids, im[1])
		}
		out[m[1]] = ids
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no HandlerConcepts entries in %s", path)
	}
	return out, nil
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found from %s", dir)
		}
		dir = parent
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
